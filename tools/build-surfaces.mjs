#!/usr/bin/env node
/* Generate the gradient surface classes.
   =====================================================================
   A 155-degree Ahimsa gradient spans a wide lightness range on purpose,
   and no single ink can carry text across all of it. This is not a tuning
   problem, it is arithmetic: the same brown that reads at 9:1 on dawn's
   pale end reads at 3:1 on indigo's deep end.

   So each gradient ships with its OWN ink. `.ah-surface--dawn` sets
   --text-heading / body / secondary / muted to values measured against
   that gradient's worst stop, and every component inside inherits them
   without knowing anything happened.

   The lever is alpha, not hue: the ink stays the system's warm brown (or
   Night's ice) and only becomes more present. That costs some of the soft
   quiet hierarchy on a gradient, which is a real trade and the right one —
   an unreadable caption is not a quieter caption.

   Where even a fully opaque ink cannot clear AA, the gradient is emitted as
   SURFACE-ONLY: it is a backdrop, and text on it belongs in an opaque card.
   That is already this system's documented pattern, not a workaround.
   ===================================================================== */

import { readTokens } from './lib/css-tokens.mjs';
import { parseHex, over, contrast, gradientStops, resolve, luminance } from './lib/color.mjs';
import { writeFileSync } from 'node:fs';

const AA = 4.5, LARGE = 3.0;

const THEMES = {
  day: {
    files: ['src/tokens/day/palette.css', 'src/tokens/day/gradients.css', 'src/tokens/day/semantic.css'],
    ink: '--neutral-900',    /* darkest ink Ahimsa allows — never pure black */
    /* Dark ink: the worst ground is the DARKEST stop. */
    worst: (stops) => stops.reduce((a, b) => (luminance(b) < luminance(a) ? b : a)),
  },
  night: {
    files: ['src/tokens/night/palette.css', 'src/tokens/night/gradients.css', 'src/tokens/night/semantic.css'],
    ink: '--neutral-50',     /* lightest ink Ahimsa allows — never pure white */
    /* Light ink: the worst ground is the LIGHTEST stop. */
    worst: (stops) => stops.reduce((a, b) => (luminance(b) > luminance(a) ? b : a)),
  },
};

const hex = (c) => '#' + [c.r, c.g, c.b].map((x) => Math.round(x).toString(16).padStart(2, '0')).join('');
const withAlpha = (c, a) => hex(c) + (a >= 0.999 ? '' : Math.round(a * 255).toString(16).padStart(2, '0'));

/* Least-present ink that still clears `target`. Quiet where it can be.
   Steps through the 8-bit alphas that can actually be written as a hex
   byte and measures THOSE, rather than finding a float that clears the bar
   and then losing it to rounding on the way out. */
function minAlpha(ink, grounds, target) {
  for (let byte = 77; byte <= 255; byte++) {      /* 77/255 = 30% */
    const a = byte / 255;
    if (grounds.every((g) => contrast(over({ ...ink, a }, g), g) >= target)) return a;
  }
  return null;
}

/* Worst ratio this ink+alpha achieves anywhere on the ramp. */
function worstRatio(ink, grounds, a) {
  return Math.min(...grounds.map((g) => contrast(over({ ...ink, a }, g), g)));
}

const summary = [];

for (const [theme, cfg] of Object.entries(THEMES)) {
  const SCOPE = `.ahimsa-${theme} `;
  const t = readTokens(cfg.files);
  const ink = parseHex(resolve(t, t.get(cfg.ink)));
  const out = [];
  const surfaceOnly = [];

  out.push(`/* Ahimsa ${theme === 'day' ? 'Day' : 'Night'} — gradient surfaces. GENERATED by tools/build-surfaces.mjs.
   Do not edit. Change the gradients or the generator instead.

   Each class sets a gradient background AND the ink that is measured to
   work on it. Put one on any element and its contents read correctly:

     <section class="ah-surface--dawn"> ... </section>

   Scoped to the theme, because a Day gradient and a Night gradient need
   different ink and two of them once shared a name. To show a Day surface
   inside a Night page (a specimen, say), wrap it: <div class="ahimsa-day">.

   ONE GRADIENT OWNS A SCREEN. Two of these side by side is the rule this
   system breaks least gladly. */\n`);

  for (const [name, value] of t) {
    if (!name.startsWith('--gradient-')) continue;
    const slug = name.replace('--gradient-', '');
    const stops = gradientStops(resolve(t, value)).map(parseHex);
    if (!stops.length) continue;
    const ground = cfg.worst(stops);   /* reported, for the comment only */

    const aHead = minAlpha(ink, stops, AA);
    if (aHead === null) {
      surfaceOnly.push(slug);
      out.push(`/* ${slug} — SURFACE ONLY. Stop ${hex(ground)} cannot carry AA text at any
   opacity (best possible ${worstRatio(ink, stops, 1).toFixed(2)}:1, with the most present ink the
   system allows). Use it as a backdrop and put text in an opaque .ah-card. */`);
      out.push(`${SCOPE}.ah-surface--${slug} { background: var(${name}); }\n`);
      continue;
    }

    const aBody = aHead;
    const aSec = aHead;
    const aMuted = minAlpha(ink, stops, LARGE);
    const r = (a) => worstRatio(ink, stops, a).toFixed(2);

    out.push(`/* ${slug} — worst stop ${hex(ground)}; heading ${r(1)}:1, body/secondary ${r(aBody)}:1, muted ${r(aMuted)}:1 */`);
    out.push(`${SCOPE}.ah-surface--${slug} {
  background: var(${name});
  --text-heading:   ${withAlpha(ink, 1)};
  --text-body:      ${withAlpha(ink, aBody)};
  --text-secondary: ${withAlpha(ink, aSec)};
  --text-muted:     ${withAlpha(ink, aMuted)};
  --border-control: ${withAlpha(ink, Math.min(1, aMuted + 0.1))};
}\n`);
    summary.push([theme, slug, hex(ground), r(aBody), r(aMuted), aMuted]);
  }

  const path = `src/tokens/${theme}/surfaces.css`;
  writeFileSync(path, out.join('\n'));
  console.log(`${path}  ${summary.filter((s) => s[0] === theme).length} text-capable, ${surfaceOnly.length} surface-only${surfaceOnly.length ? ': ' + surfaceOnly.join(', ') : ''}`);
}

if (process.argv.includes('--report')) {
  console.log('\ntheme  gradient             worst stop  heading  muted  muted alpha');
  for (const [th, slug, g, rh, rm, am] of summary) {
    console.log(`${th.padEnd(7)}${slug.padEnd(21)}${g}     ${rh.padStart(5)}  ${rm.padStart(5)}   ${(am * 100).toFixed(0)}%`);
  }
}
